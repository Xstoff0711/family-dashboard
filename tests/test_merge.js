// Prüft das Zusammenführen (merge3) aus static/index.html. Aufruf: node tests/test_merge.js
const fs = require('fs'), path = require('path');
const h = fs.readFileSync(path.join(__dirname, '..', 'static', 'index.html'), 'utf8');
const src = h.slice(h.indexOf('const clone = v'), h.indexOf('function save(k){'));
const merge3 = new Function(src + '; return merge3;')();
let fails = 0;
const t = (n, a, b) => { const ok = JSON.stringify(a) === JSON.stringify(b); if (!ok) fails++; console.log((ok ? '  ok    ' : '  FEHLER ') + n + (ok ? '' : '  ' + JSON.stringify(a))); };
const base = [{id:'c1', title:'Wäsche', done:{}}, {id:'c2', title:'Müll', done:{}}];
const me = [{id:'c1', title:'Wäsche', done:{d:true}}, {id:'c2', title:'Müll', done:{}}];
const her = [{id:'c1', title:'Wäsche', done:{}}, {id:'c2', title:'Müll', done:{d:true}}];
t('Haken an verschiedenen Aufgaben bleiben beide', merge3(base, her, me).map(c => Object.keys(c.done).length), [1, 1]);
t('Haken entfernen und andere Änderung', merge3(me, base, [{id:'c1', title:'Wäsche', done:{d:true}}, {id:'c2', title:'Müll neu', done:{}}]).map(c => [c.title, Object.keys(c.done).length]), [['Wäsche', 0], ['Müll neu', 0]]);
t('beide fügen Aufgaben hinzu', merge3(base, [...base, {id:'a'}], [...base, {id:'b'}]).map(c => c.id), ['c1', 'c2', 'a', 'b']);
t('gelöscht vs. abgehakt: Haken gewinnt', merge3(base, me, [base[1]]).map(c => c.id), ['c1', 'c2']);
t('Löschen von Unverändertem', merge3(base, base.slice(), [base[1]]).map(c => c.id), ['c2']);
const sb = {checked:{}, manual:[{id:'m1', text:'Milch', done:false}], bought:{}};
const sm = {checked:{'w|ei':true}, manual:[{id:'m1', text:'Milch', done:true}], bought:{}};
const st = {checked:{'w|brot':true}, manual:[{id:'m1', text:'Milch', done:false}, {id:'m2', text:'Käse', done:false}], bought:{}};
const r = merge3(sb, sm, st);
t('Einkauf zusammengeführt', [Object.keys(r.checked).sort(), r.manual.map(m => m.text + ':' + m.done)], [['w|brot', 'w|ei'], ['Milch:true', 'Käse:false']]);
const pb = {w:{0:{din:[{r:'x', who:'all'}]}}};
t('Plan: beide fügen ein Gericht hinzu', merge3(pb, {w:{0:{din:[{r:'x', who:'all'}, {r:'y', who:'all'}]}}}, {w:{0:{din:[{r:'x', who:'all'}, {r:'z', who:'all'}]}}}).w[0].din.map(e => e.r), ['x', 'z', 'y']);
t('Plan: ich entferne, sie fügt hinzu', merge3(pb, {w:{0:{din:[]}}}, {w:{0:{din:[{r:'x', who:'all'}, {r:'z', who:'all'}]}}}).w[0].din.map(e => e.r), ['z']);
t('Doppelte Einträge bleiben erhalten', merge3({a:[1]}, {a:[1, 1]}, {a:[1, 2]}).a, [1, 2, 1]);
t('gleicher Wert von beiden geändert: eigene Eingabe', merge3({t:'a'}, {t:'mine'}, {t:'theirs'}).t, 'mine');
t('Schlüsselreihenfolge spielt keine Rolle', merge3({a:1, b:2}, {b:2, a:1}, {a:1, b:3}), {a:1, b:3});
t('kein Server-Stand vorhanden', merge3(undefined, {x:1}, null), {x:1});
console.log(fails ? `\n${fails} Fehler.` : '\nAlle Merge-Prüfungen bestanden.');
process.exit(fails ? 1 : 0);
